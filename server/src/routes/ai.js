
import { Router } from 'express';
import mongoose from 'mongoose';
import { GoogleGenerativeAI } from '@google/generative-ai';
import Ticket from '../models/Ticket.js';
import { retrieveRelevantNotes } from '../services/retrieval.js';

const router = Router();

function createMockAnalysis(ticket) {
  const text = `${ticket.title} ${ticket.description}`.toLowerCase();

  let category = 'Other';
  let priority = 'Medium';

  if (/login|password|account|sign in/.test(text)) {
    category = 'Account';
  } else if (/database|mongodb|query/.test(text)) {
    category = 'Database';
  } else if (/api|endpoint|request/.test(text)) {
    category = 'API';
  } else if (/slow|performance|loading|timeout/.test(text)) {
    category = 'Performance';
  } else if (/bug|error|crash|not working/.test(text)) {
    category = 'Bug';
  }

  if (/critical|down|unavailable|all users/.test(text)) {
    priority = 'Critical';
  } else if (/urgent|blocked|cannot|unable|failed/.test(text)) {
    priority = 'High';
  } else if (/minor|suggestion|cosmetic/.test(text)) {
    priority = 'Low';
  }

  return {
    summary: `The requester reported: ${ticket.title}. The issue needs investigation based on the provided description.`,
    category,
    priority,
    suggestedReply: `Hello,\n\nThank you for reporting this issue. Our support team has received your request and will investigate it. We may contact you if additional information is needed.\n\nThank you for your patience.`,
    reasoning: 'This is a local demo analysis based on simple keyword matching. It is not a response generated by Gemini.'
  };
}

router.post('/analyze', async (req, res, next) => {
  try {
    const { ticketId } = req.body;

    if (!mongoose.isValidObjectId(ticketId)) {
      return res.status(400).json({
        message: 'A valid ticketId is required.'
      });
    }

    const ticket = await Ticket.findById(ticketId);

    if (!ticket) {
      return res.status(404).json({
        message: 'Ticket not found.'
      });
    }

    const notes = retrieveRelevantNotes(
      `${ticket.title} ${ticket.description}`
    );

    let parsed;
    let source = 'Gemini';

    if (process.env.GEMINI_API_KEY) {
      try {
        const genAI = new GoogleGenerativeAI(
          process.env.GEMINI_API_KEY
        );

        const model = genAI.getGenerativeModel({
          model: 'gemini-3.8-flash'
        });

        const context = notes.length
          ? notes.map((note, index) =>
              `${index + 1}. ${note.title}: ${note.content}`
            ).join('\n')
          : 'No matching internal knowledge-base notes were found. Do not invent company policies or technical facts.';

        const prompt = `You are DevAssist AI, a careful technical support copilot.
Analyze the support ticket using the retrieved notes as optional context.
Do not claim that you performed actions. Do not invent facts.
Return ONLY valid JSON with exactly these keys:
{"summary":"2 sentence summary","category":"Bug|Account|API|Performance|Database|Other","priority":"Low|Medium|High|Critical","suggestedReply":"Helpful concise reply to the requester","reasoning":"Brief reason for category and priority"}
Ticket title: ${ticket.title}
Ticket description: ${ticket.description}
Retrieved knowledge-base notes:
${context}`;

        const result = await model.generateContent(prompt);
        const raw = result.response.text()
          .replace(/```json|```/g, '')
          .trim();

        parsed = JSON.parse(raw);
      } catch (error) {
        console.warn(
          'Gemini unavailable. Using local demo analysis:',
          error.message
        );

        parsed = createMockAnalysis(ticket);
        source = 'Local Demo AI';
      }
    } else {
      parsed = createMockAnalysis(ticket);
      source = 'Local Demo AI';
    }

    const allowedPriorities = [
      'Low',
      'Medium',
      'High',
      'Critical'
    ];

    if (!allowedPriorities.includes(parsed.priority)) {
      parsed.priority = 'Medium';
    }

    const analysis = {
      summary: String(parsed.summary || ''),
      category: String(parsed.category || 'Other'),
      priority: parsed.priority,
      suggestedReply: String(parsed.suggestedReply || ''),
      sources: notes.map(note => note.title),
      source
    };

    ticket.aiAnalysis = analysis;
    await ticket.save();

    res.json({
      analysis,
      reasoning: String(parsed.reasoning || ''),
      retrievedNotes: notes.map(note => note.title),
      source
    });

  } catch (error) {
    next(error);
  }
});

export default router;
